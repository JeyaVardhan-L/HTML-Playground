from django.db import models


class Student(models.Model):
    """
    Student model representing student entities in SQLite database.
    Fields:
    - id: Primary Key (auto-generated by Django)
    - name: Full name of the student
    - department: Enrolled academic department
    - year: Current year of study
    """
    name = models.CharField(max_length=100)
    department = models.CharField(max_length=100)
    year = models.CharField(max_length=20)

    def __str__(self):
        return f"{self.id} - {self.name} ({self.department})"
